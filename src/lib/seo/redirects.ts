import type { Db } from "mongodb";

export type RedirectType = "301" | "302";

export interface RedirectRule {
  source: string;
  destination: string;
  type: RedirectType;
  note?: string;
  createdAt: Date;
}

export interface StoredRedirect extends RedirectRule {
  userId: string;
  domain: string;
}

export function normalizeRedirectPath(value: string): string {
  const path = value.trim();
  if (!path) return "";
  if (!path.startsWith("/")) return `/${path}`;
  return path;
}

export function validateRedirectRule(source: string, destination: string): string | null {
  if (!source.trim()) return "Source path is required.";
  if (!source.trim().startsWith("/")) return "Source must be a path starting with /.";
  if (!destination.trim()) return "Destination is required.";
  if (source.trim() === destination.trim()) return "Source and destination must differ.";
  return null;
}

export async function listRedirects(db: Db, userId: string, domain: string): Promise<RedirectRule[]> {
  const records = await db.collection<StoredRedirect>("website_redirects")
    .find({ userId, domain }, { projection: { _id: 0, userId: 0, domain: 0 } })
    .sort({ createdAt: -1 })
    .limit(500)
    .toArray();
  return records as RedirectRule[];
}

export async function upsertRedirect(db: Db, userId: string, domain: string, rule: Omit<RedirectRule, "createdAt">): Promise<void> {
  await db.collection<StoredRedirect>("website_redirects").updateOne(
    { userId, domain, source: rule.source },
    { $set: { destination: rule.destination, type: rule.type, note: rule.note ?? "", updatedAt: new Date() }, $setOnInsert: { createdAt: new Date() } },
    { upsert: true },
  );
}

export async function deleteRedirect(db: Db, userId: string, domain: string, source: string): Promise<void> {
  await db.collection<StoredRedirect>("website_redirects").deleteOne({ userId, domain, source });
}

export function exportNginx(rules: RedirectRule[]): string {
  const lines = rules.map((r) => {
    const flag = r.type === "301" ? "permanent" : "redirect";
    return `rewrite ^${r.source}$ ${r.destination} ${flag};`;
  });
  return `# Generated by SEO Studio\n# Place inside your server {} block\n\n${lines.join("\n")}`;
}

export function exportApache(rules: RedirectRule[]): string {
  const lines = rules.map((r) => `Redirect ${r.type} ${r.source} ${r.destination}`);
  return `# Generated by SEO Studio\n# Place in .htaccess or VirtualHost\n\n${lines.join("\n")}`;
}

export function exportVercel(rules: RedirectRule[]): string {
  const redirects = rules.map((r) => ({
    source: r.source,
    destination: r.destination,
    permanent: r.type === "301",
  }));
  return JSON.stringify({ redirects }, null, 2);
}

export function exportCsv(rules: RedirectRule[]): string {
  const header = "source,destination,type,note";
  const rows = rules.map((r) => `"${r.source}","${r.destination}","${r.type}","${(r.note ?? "").replace(/"/g, '""')}"`);
  return [header, ...rows].join("\n");
}
